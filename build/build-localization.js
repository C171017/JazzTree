#!/usr/bin/env node
/**
 * Merge the hand-authored Simplified Chinese fragments and create the two
 * runtime forms consumed by the web app and the iOS synchronisation step.
 *
 * Source:    locales/zh-CN/*.json
 * Generated: data/localization.zh-CN.json
 *            data/localization.zh-CN.js (file:// compatible browser global)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'locales', 'zh-CN');
const sections = ['genres', 'lineage', 'albums', 'paths'];
const merged = Object.fromEntries(sections.map((section) => [section, {}]));

for (const filename of readdirSync(sourceDir).filter((name) => name.endsWith('.json')).sort()) {
  const fragment = JSON.parse(readFileSync(join(sourceDir, filename), 'utf8'));
  for (const section of sections) {
    for (const [id, value] of Object.entries(fragment[section] ?? {})) {
      if (Object.hasOwn(merged[section], id)) {
        throw new Error(`${filename}: duplicate ${section} id "${id}"`);
      }
      merged[section][id] = value;
    }
  }
  const unknown = Object.keys(fragment).filter((key) => !sections.includes(key));
  if (unknown.length) throw new Error(`${filename}: unknown top-level keys: ${unknown.join(', ')}`);
}

const payload = { locale: 'zh-CN', ...merged };
const json = JSON.stringify(payload, null, 2) + '\n';
writeFileSync(join(root, 'data', 'localization.zh-CN.json'), json);
writeFileSync(
  join(root, 'data', 'localization.zh-CN.js'),
  `/* GENERATED by build/build-localization.js — do not edit. */\nwindow.__JAZZ_ZH_CN__ = ${JSON.stringify(payload)};\n`
);

console.log(
  `wrote Simplified Chinese locale — ${Object.keys(merged.genres).length} genres, ` +
  `${Object.keys(merged.lineage).length} edges, ${Object.keys(merged.albums).length} albums, ` +
  `${Object.keys(merged.paths).length} paths`
);
