#!/usr/bin/env node
/**
 * Extracts the localisation tables out of js/i18n.js into
 * ios/Packages/JazzTreeCore/Sources/JazzTreeCore/Resources/localization.json, so the iOS app and the web app share
 * one source of truth for translated strings instead of drifting apart.
 *
 * Run:  node build/extract-i18n.js
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
/**
 * i18n.js is a module with top-level `const` tables. Rather than parse it, we
 * import it and read the tables back through its own accessors — that way the
 * extraction can never disagree with what the web app actually renders.
 * setLocale() sets document.documentElement.lang, so it needs a DOM stub here.
 */
globalThis.document ??= { documentElement: {} };
const mod = await import(new URL('../js/i18n.js', import.meta.url).href);
const { genres, families, eras } = JSON.parse(readFileSync(join(root, 'data/genres.json'), 'utf8'));
const paths = JSON.parse(readFileSync(join(root, 'data/paths.json'), 'utf8'));
const editorial = JSON.parse(readFileSync(join(root, 'data/localization.zh-CN.json'), 'utf8'));

const ASPECTS = [
  'harmony', 'rhythm', 'form', 'instrumentation', 'improvisation',
  'timbre', 'repertoire', 'social-context', 'technology',
];
const EDGE_TYPES = [
  'direct-descendant', 'reaction-against', 'fusion-of', 'parallel-influence', 'revival-of',
];

// Exact key parity is mandatory. Otherwise t() could conceal a missing Chinese
// string behind a fallback while the generated iOS resource still looks valid.
const englishUIKeys = mod.uiTranslationKeys('en');
const chineseUIKeys = mod.uiTranslationKeys('zh-CN');
const englishUISet = new Set(englishUIKeys);
const chineseUISet = new Set(chineseUIKeys);
const missingChineseUI = englishUIKeys.filter((key) => !chineseUISet.has(key));
const extraChineseUI = chineseUIKeys.filter((key) => !englishUISet.has(key));
if (missingChineseUI.length || extraChineseUI.length) {
  throw new Error(
    `Web UI localisation key mismatch. Missing zh-CN: ${missingChineseUI.join(', ') || 'none'}; ` +
    `extra zh-CN: ${extraChineseUI.join(', ') || 'none'}`
  );
}
const uiKeys = englishUIKeys.filter((key) => !key.startsWith('meta.'));

// iOS-only strings. The web app has no rail, no tab bar and no settings screen, so
// these cannot come from js/i18n.js — but everything the web app *does* have is
// still read from there, so the shared strings can never drift.
const iosExtras = JSON.parse(readFileSync(join(root, 'build/ios-strings.json'), 'utf8')).strings;
const localeIndex = { en: 0, 'zh-CN': 1 };

function forLocale(locale) {
  mod.setLocale(locale);
  const extras = Object.fromEntries(
    Object.entries(iosExtras).map(([key, values]) => [key, values[localeIndex[locale] ?? 0]])
  );
  return {
    ui: { ...Object.fromEntries(uiKeys.map((k) => [k, mod.t(k)])), ...extras },
    genreNames: Object.fromEntries(genres.map((g) => [g.id, mod.genreName(g)])),
    genreOneLines: Object.fromEntries(genres.map((g) => [g.id, mod.genreOneLine(g)])),
    families: Object.fromEntries(families.map((f) => [f.id, {
      name: mod.familyName(f), short: mod.familyShort(f), blurb: mod.familyBlurb(f),
    }])),
    eras: Object.fromEntries(eras.map((e) => [e.id, mod.eraName(e)])),
    aspects: Object.fromEntries(ASPECTS.map((a) => [a, mod.aspectLabel(a)])),
    edgeTypes: Object.fromEntries(EDGE_TYPES.map((t) => [t, mod.edgeTypeLabel(t)])),
    edgeDescriptions: Object.fromEntries(EDGE_TYPES.map((t) => [t, mod.edgeDescription(t)])),
    paths: Object.fromEntries(paths.map((p) => [p.id, {
      name: mod.pathText(p, 'name'),
      subtitle: mod.pathText(p, 'subtitle'),
      blurb: mod.pathText(p, 'blurb'),
    }])),
    genreContent: locale === 'zh-CN' ? editorial.genres : {},
    lineageContent: locale === 'zh-CN' ? editorial.lineage : {},
    albumContent: locale === 'zh-CN' ? editorial.albums : {},
    pathContent: locale === 'zh-CN' ? editorial.paths : {},
  };
}

const out = {
  note: 'GENERATED by build/extract-i18n.js from js/i18n.js — do not hand-edit.',
  locales: mod.LOCALES,
  tables: Object.fromEntries(mod.LOCALES.map((l) => [l.id, forLocale(l.id)])),
};
mod.setLocale('en');

const dir = join(root, 'ios/Packages/JazzTreeCore/Sources/JazzTreeCore/Resources');
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'localization.json'), JSON.stringify(out, null, 2) + '\n');

const en = out.tables.en;
console.log(
  `wrote ios/Packages/JazzTreeCore/Sources/JazzTreeCore/Resources/localization.json — ${out.locales.length} locales, ` +
  `${Object.keys(en.ui).length} UI keys, ${Object.keys(en.genreNames).length} genres, ` +
  `${Object.keys(en.paths).length} paths, full editorial content`
);

// --- Guard: every key the Swift code asks for must exist in both tables. -------
// Without this, a typo'd key silently renders as the raw key string on device.
import { readdirSync, statSync } from 'node:fs';

function swiftFiles(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) return swiftFiles(full);
    return full.endsWith('.swift') ? [full] : [];
  });
}

const appDir = join(root, 'ios/JazzTree');
let referenced = new Set();
try {
  for (const file of swiftFiles(appDir)) {
    const text = readFileSync(file, 'utf8');
    for (const match of text.matchAll(/\bt\("([a-zA-Z0-9._]+)"/g)) referenced.add(match[1]);
    // Keys assembled from enum raw values, e.g. "panel.\(tier.rawValue)".
    for (const match of text.matchAll(/"((?:ios\.|panel\.|grid\.sort\.|confidence\.|difficulty\.)[a-zA-Z0-9._]*)\\\(/g)) {
      referenced.add(match[1] + '*');
    }
  }
} catch {
  // The app directory may not exist yet; the guard is best-effort.
}

const known = new Set(Object.keys(out.tables.en.ui));
const missing = [...referenced]
  .filter((key) => !key.endsWith('*'))
  .filter((key) => !known.has(key));

if (missing.length) {
  console.error(`\nERROR: ${missing.length} localisation key(s) used by the iOS app are missing:`);
  for (const key of missing.sort()) console.error(`  ${key}`);
  console.error('Add them to build/ios-strings.json (or js/i18n.js if the web app needs them too).');
  process.exit(1);
}
const untranslated = [...known].filter(
  (key) => key.startsWith('ios.') && out.tables['zh-CN'].ui[key] === out.tables.en.ui[key]
);
if (untranslated.length) {
  console.warn(`WARN: ${untranslated.length} iOS key(s) are identical in both locales: ${untranslated.join(', ')}`);
}
console.log(`checked ${referenced.size} keys referenced by the iOS app — all resolve`);
